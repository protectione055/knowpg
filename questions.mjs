function reference(path, anchor, symbol) {
  return {
    label: `${path.split('/').at(-1)} · ${symbol}`,
    url: `https://github.com/postgres/postgres/blob/${revision}/${path}#L${anchor}`,
  }
}

function documentation(page, label) {
  return { label, url: `https://www.postgresql.org/docs/18/${page}` }
}

